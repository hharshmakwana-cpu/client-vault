const BASE = process.env.BASE || 'http://localhost:8123/';
const { chromium } = require('playwright');
const OUT = require('fs').mkdtempSync(require('path').join(require('os').tmpdir(), 'cv-test-')), R = [];
const check = (n, ok, i = '') => R.push(`${ok ? 'PASS' : 'FAIL'}  ${n}${i ? '  — ' + i : ''}`);
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, acceptDownloads: true });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('dialog', d => d.accept());
  await p.route('**/config.js', r => r.fulfill({ contentType: 'text/javascript', body: 'window.CLIENT_VAULT_CONFIG={apiKey:""};' }));
  const wait = ms => p.waitForTimeout(ms || 650);
  await p.goto(BASE);
  await p.fill('#p1', 'testpassword123'); await p.fill('#p2', 'testpassword123'); await p.click('#go'); await wait();
  await p.click('[data-act="skip"]'); await wait();
  await p.evaluate(() => go('firm', { from: 'list' })); await wait();
  await p.fill('#f_name', 'Makwana & Associates'); await p.fill('#f_addr1', '301, Shivalik Plaza, Ashram Road'); await p.fill('#f_city', 'Ahmedabad'); await p.fill('#f_pin', '380009');
  await p.fill('#f_signatory', 'CA Harsh Makwana');
  const [fc] = await Promise.all([p.waitForEvent('filechooser'), p.click('[data-act="logo"]')]);
  await fc.setFiles(require('path').join(__dirname, 'fixtures', 'logo.png')); await wait(800);
  check('logo preview in firm details', await p.locator('#logoBox img').count() === 1);
  await p.screenshot({ path: OUT + '/l1-firm.png' });
  await p.click('[data-act="save"]'); await wait();
  const lg = await p.evaluate(() => logoOf() && { w: logoOf().w, h: logoOf().h, kb: Math.round(logoOf().src.length / 1024) });
  check('logo saved, resized as JPEG', lg && lg.w <= 480 && lg.h <= 240, JSON.stringify(lg));
  check('logo on home screen', await p.locator('.mini-brand img').count() === 1);
  await p.screenshot({ path: OUT + '/l2-home.png' });
  await p.evaluate(() => go('edit', null)); await wait();
  await p.fill('[data-k="name"]', 'Ramesh Kumar Patel'); await p.fill('[data-k="pan"]', 'ABCPP1234F');
  await p.click('[data-act="save"]'); await wait(900);
  if (await p.evaluate(() => cur.v) === 'comp') { await p.click('[data-act="save"]'); await wait(900); }
  await p.click('[data-act="fees"]'); await wait();
  await p.fill('#amt', '12500'); await p.fill('#fdesc', 'ITR filing AY 2026-27'); await p.click('[data-act="fadd"]'); await wait();
  await p.click('[data-act="doc"]'); await wait();
  check('logo on invoice preview', await p.locator('.paper .pp-logo').count() === 1);
  await p.screenshot({ path: OUT + '/l3-invoice.png', fullPage: true });
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('[data-act="dl"]')]);
  await dl.saveAs(OUT + '/logo-invoice.pdf'); await wait();
  await p.setViewportSize({ width: 1280, height: 800 }); await wait(300);
  await p.click('[data-tab="list"]'); await wait();
  check('logo in sidebar', await p.locator('#brandI img').count() === 1 && (await p.locator('#brandName').textContent()) === 'Makwana & Associates');
  await p.screenshot({ path: OUT + '/l4-desktop.png' });
  await p.setViewportSize({ width: 390, height: 844 });
  await p.evaluate(() => lock()); await wait();
  check('logo + firm name on unlock screen', await p.locator('.lock-icon.brand-logo img').count() === 1 && (await p.locator('.lock h1').textContent()) === 'Makwana & Associates');
  await p.screenshot({ path: OUT + '/l5-unlock.png' });
  check('no script errors', !errs.length, errs.join(' | '));
  console.log(R.join('\n')); await b.close(); process.exit(R.some(r => r.startsWith('FAIL')) ? 1 : 0);
})();
